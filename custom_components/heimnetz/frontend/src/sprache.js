// Sprache der Seite (WU-0006): Deutsch oder Englisch, nach der Sprache des Nutzers in Home Assistant
// (hass.locale.language, sonst hass.language). „de“ und jede Variante davon (de-CH …) zeigt Deutsch, alles andere
// Englisch. Die Texte stehen deutsch im Code und sind zugleich der Schlüssel: t('Heute {uhr}', { uhr }) liefert auf
// Deutsch den Text selbst, auf Englisch die Zeile aus EN. Platzhalter {name} füllt t() aus `werte`.
// merke('…') kennzeichnet Texte in Konstanten, die erst beim Zeichnen über t() laufen – nur, damit der Seitentest sie
// findet und prüft, dass zu jedem Text eine englische Zeile da ist (tests/seite/sprache.test.mjs).
// Texte, die die Integration fertig liefert (Befunde, Prüfungen, Ereignisse …), übersetzt sie selbst.

let aktiv = 'en';

/** Sprache aus hass wählen; liefert „de“ oder „en“. */
export function waehle(hass) {
  const l = String((hass && ((hass.locale && hass.locale.language) || hass.language)) || '').toLowerCase();
  aktiv = l === 'de' || l.startsWith('de-') || l.startsWith('de_') ? 'de' : 'en';
  return aktiv;
}

/** Gewählte Sprache („de“ oder „en“) – auch für Zahlen- und Datumsformat. */
export const sprache = () => aktiv;

/** Text in der gewählten Sprache; fehlt eine englische Zeile, bleibt der deutsche Text (der Test meldet das). */
export function t(text, werte) {
  const vorlage = aktiv === 'de' ? text : (EN[text] ?? text);
  return werte ? vorlage.replace(/\{(\w+)\}/g, (ganz, k) => (k in werte ? String(werte[k]) : ganz)) : vorlage;
}

/** Kennzeichnet einen Text zum Übersetzen, ohne ihn zu übersetzen (Konstanten). */
export const merke = (text) => text;

/** Liste [[wert, text], …] mit übersetzten Texten (für seg()). */
export const tl = (liste) => liste.map(([k, text]) => [k, t(text)]);

